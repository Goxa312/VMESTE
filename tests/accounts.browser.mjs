import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { createRequire } from "node:module";
const { chromium } = createRequire(import.meta.url)(process.env.QA_PLAYWRIGHT || "playwright");
const browser = await chromium.launch({executablePath:process.env.QA_CHROME,headless:true,args:["--mute-audio"]});
const base=process.env.TEST_BASE_URL || "http://127.0.0.1:8790";
const login="qa_"+randomUUID().slice(0,8), password=randomUUID();
try {
  const first=await browser.newContext(), second=await browser.newContext();
  const host=await first.newPage(), returned=await second.newPage();
  await host.goto(base);
  await host.getByRole("button",{name:"Регистрация",exact:true}).click();
  const registration=host.getByRole("dialog");
  await registration.getByLabel("Логин").fill(login); await registration.getByLabel("Пароль").fill(password);
  await registration.getByRole("button",{name:"Создать аккаунт"}).click();
  await host.getByRole("button",{name:"Профиль: "+login}).waitFor();
  await host.getByRole("button",{name:"Все 100 фильмов"}).click();
  const chart=host.getByRole("dialog");
  await chart.locator(".rank-save").first().click(); await chart.locator(".rank-save[aria-pressed=true]").waitFor();
  await chart.getByRole("button",{name:"Закрыть"}).click();
  await host.getByRole("navigation").getByRole("button",{name:"Создать комнату"}).click();
  const form=host.getByRole("dialog");
  assert.equal(await form.getByLabel("Ваше имя").inputValue(),login);
  await form.getByLabel("Ссылка на фильм").fill("https://example.org/watch/account-screen");
  await form.getByLabel("Название фильма",{exact:true}).fill("Проверка профиля");
  await form.getByRole("button",{name:"Создать комнату"}).click();
  await host.waitForURL(/\/room\/[a-f0-9]{12}$/); await host.getByText("Вы ведущий",{exact:false}).first().waitFor();
  const address=host.url();
  await returned.goto(base);
  await returned.getByRole("button",{name:"Вход",exact:true}).click();
  const signin=returned.getByRole("dialog");
  await signin.getByLabel("Логин").fill(login); await signin.getByLabel("Пароль").fill(password);
  await signin.getByRole("button",{name:"Войти",exact:true}).click();
  await returned.getByRole("button",{name:"Профиль: "+login}).waitFor();
  await returned.getByRole("navigation").getByRole("link",{name:"Наш список"}).click();
  assert.equal(await returned.locator(".chart-results .rank-save[aria-pressed=true]").count(),1);
  await returned.getByRole("navigation").getByRole("link",{name:"Главная"}).click();
  await returned.getByRole("link",{name:/Открыть комнату:.*Проверка профиля/}).click();
  await returned.getByRole("button",{name:"Выбрать фильм",exact:true}).waitFor();
  assert.equal(returned.url(),address);
  await returned.getByRole("link",{name:"Together Tonight — на главную"}).click();
  await returned.getByRole("button",{name:"Профиль: "+login}).click(); await returned.getByRole("button",{name:"Выйти из аккаунта"}).click();
  await returned.getByRole("button",{name:"Вход",exact:true}).waitFor();
  assert.equal(await returned.getByRole("link",{name:/Открыть комнату:.*Проверка профиля/}).count(),0);
  console.log("PASS: real sign-up, signed-in room creation, bookmarks and host controls in a second browser, logout");
} finally { await browser.close(); }
